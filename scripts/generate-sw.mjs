// Post-build step: writes out/sw.js with a precache list of every file in the
// static export, so the whole app works offline after the first visit.
import { createHash } from "node:crypto";
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative, sep } from "node:path";

const outDir = "out";
const basePath = process.env.NEXT_PUBLIC_BASE_PATH || "";

function walk(dir) {
  return readdirSync(dir).flatMap((name) => {
    const p = join(dir, name);
    return statSync(p).isDirectory() ? walk(p) : [p];
  });
}

const files = walk(outDir)
  .map((f) => relative(outDir, f).split(sep).join("/"))
  .filter((f) => f !== "sw.js" && !f.endsWith(".map") && f !== "404.html" && !f.startsWith("_next/static/media/"));

const hash = createHash("sha256");
for (const f of files.sort()) hash.update(f).update(readFileSync(join(outDir, f)));
const version = hash.digest("hex").slice(0, 12);

// Directory pages are requested as "/path/" (trailingSlash export).
const urls = files.map((f) => `${basePath}/${f.replace(/(^|\/)index\.html$/, "$1")}`);

const sw = `// Generated by scripts/generate-sw.mjs. Do not edit.
const CACHE = "kerala-trip-${version}";
const BASE = ${JSON.stringify(basePath)};
const PRECACHE = ${JSON.stringify(urls)};

self.addEventListener("install", (event) => {
  event.waitUntil(caches.open(CACHE).then((c) => c.addAll(PRECACHE)).then(() => self.skipWaiting()));
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith("kerala-trip-") && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener("fetch", (event) => {
  const req = event.request;
  if (req.method !== "GET") return;
  const url = new URL(req.url);
  if (url.origin !== self.location.origin) return; // maps, WhatsApp etc. go straight to the network

  if (req.mode === "navigate") {
    // Pages: cache first (the app is static), falling back to the network,
    // then to the home page so the app still opens offline.
    let path = url.pathname;
    if (!path.endsWith("/") && !path.includes(".")) path += "/";
    event.respondWith(
      caches.match(path).then((hit) => hit || fetch(req).catch(() => caches.match(BASE + "/"))),
    );
    return;
  }

  event.respondWith(
    // Static files never vary by query; ?_rsc=… on route payloads is a cache-buster.
    caches.match(req, { ignoreSearch: true }).then(
      (hit) =>
        hit ||
        fetch(req).then((res) => {
          if (res.ok && res.type === "basic") {
            const copy = res.clone();
            caches.open(CACHE).then((c) => c.put(req, copy));
          }
          return res;
        }),
    ),
  );
});
`;

writeFileSync(join(outDir, "sw.js"), sw);
console.log(`sw.js written: ${urls.length} files precached, cache ${version}`);
